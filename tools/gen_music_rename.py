"""Regenerate src/music_rename.h (run after adding a global to src/nes.c):
    python tools/gen_music_rename.py [cc]
Compiles nes.c, lists its global symbols and renames each to mc_<name>, so
src/music_core.c can include nes.c as a second, private NES."""
import subprocess, sys, tempfile, os
cc = sys.argv[1] if len(sys.argv) > 1 else 'gcc'
obj = os.path.join(tempfile.mkdtemp(), 'nes.o')
subprocess.check_call([cc, '-O2', '-w', '-c', '-o', obj, 'src/nes.c'])
out = subprocess.check_output(['nm', obj]).decode()
syms = sorted({l.split()[2] for l in out.splitlines() if len(l.split()) == 3 and l.split()[1] in 'TDBCR'})
syms.append('host_frame')
with open('src/music_rename.h', 'w') as f:
    f.write('/* Generated by tools/gen_music_rename.py: every global symbol of nes.c, renamed\n'
            '   for the music core\'s private copy (src/music_core.c). */\n')
    for s in syms: f.write('#define %s mc_%s\n' % (s, s))
print(len(syms), 'symbols')
